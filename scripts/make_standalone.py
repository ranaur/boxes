#!/usr/bin/env python3
"""
Build standalone single-file versions of the boxes command line tools.

Each generated file embeds the complete ``boxes`` package (including all
generators) as a zipped, base64 encoded blob.  On first run the blob is
extracted to a temporary directory which is then put on ``sys.path``.

The files are written to ``scripts/standalone/``.  This location is
deliberate: it keeps ``Path(__file__).parent.parent.parent`` pointing at
the repository root (used e.g. for ``examples.yml``) and lets
``boxesserver`` find ``../static`` through its existing fallback chain.

Usage: python scripts/make_standalone.py
"""
from __future__ import annotations

import base64
import hashlib
import io
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKAGE_DIR = os.path.join(ROOT, "boxes")
OUT_DIR = os.path.join(ROOT, "scripts", "standalone")

# standalone name -> source file (relative to ROOT)
TARGETS = {
    "boxes": "boxes/scripts/boxes_main.py",
    "boxes_cli": "boxes/scripts/boxes_cli.py",
    "boxes_proxy": "boxes/scripts/boxes_proxy.py",
    "boxes_server": "boxes/scripts/boxesserver.py",
    "boxes_generator": "boxes/scripts/boxes_generator.py",
    "boxes2inkscape": "scripts/boxes2inkscape",
    "boxes2pot": "scripts/boxes2pot",
}

BOOTSTRAP = '''\
import base64 as _b64
import hashlib as _hl
import os as _os
import sys as _sys
import tempfile as _tf
import zipfile as _zf
from io import BytesIO as _BIO

_BUNDLE = _b64.b64decode("""
{bundle}
""")
_tag = _hl.sha256(_BUNDLE).hexdigest()[:16]
_dest = _os.path.join(_tf.gettempdir(), "boxes-standalone-" + _tag)
if not _os.path.exists(_os.path.join(_dest, ".ready")):
    _zf.ZipFile(_BIO(_BUNDLE)).extractall(_dest)
    with open(_os.path.join(_dest, ".ready"), "w") as _f:
        _f.write("ok")
_sys.path.insert(0, _dest)
del _b64, _hl, _os, _sys, _tf, _zf, _BIO, _BUNDLE, _tag, _dest
'''


def build_bundle() -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for dirpath, dirnames, filenames in os.walk(PACKAGE_DIR):
            dirnames[:] = [d for d in dirnames if d != "__pycache__" and d != ".continue"]
            for filename in sorted(filenames):
                if filename.endswith((".pyc", ".pyo")):
                    continue
                full = os.path.join(dirpath, filename)
                arc = os.path.relpath(full, ROOT)
                zf.write(full, arc)
    return buf.getvalue()


def split_source(text: str):
    """Return (coding_line, future_imports, body) with shebang/future lines removed."""
    lines = text.splitlines(keepends=True)
    coding = None
    future = []
    body = []
    for i, line in enumerate(lines):
        stripped = line.strip()
        if i == 0 and stripped.startswith("#!"):
            continue
        if coding is None and re.match(r"#\s*-\*-\s*coding[:=]", stripped):
            coding = line
            continue
        if re.match(r"from\s+__future__\s+import", stripped):
            future.append(line)
            continue
        body.append(line)
    # drop leading blank lines left behind
    while body and not body[0].strip():
        body.pop(0)
    return coding, future, "".join(body)


def main() -> int:
    bundle = build_bundle()
    b64 = base64.b64encode(bundle).decode("ascii")
    # wrap base64 at 76 chars to keep lines reasonable
    b64 = "\n".join(b64[i:i + 76] for i in range(0, len(b64), 76))
    bootstrap = BOOTSTRAP.format(bundle=b64)

    os.makedirs(OUT_DIR, exist_ok=True)
    for name, rel in TARGETS.items():
        src_path = os.path.join(ROOT, rel)
        with open(src_path, encoding="utf-8") as f:
            text = f.read()
        coding, future, body = split_source(text)

        out = ["#!/usr/bin/env python3\n"]
        if coding:
            out.append(coding if coding.endswith("\n") else coding + "\n")
        out.append(
            "# Standalone build of '%s' -- embeds the boxes library.\n"
            "# Generated by scripts/make_standalone.py -- do not edit.\n" % name
        )
        out.extend(future)
        out.append("\n")
        out.append(bootstrap)
        out.append("\n")
        out.append(body)

        dest = os.path.join(OUT_DIR, name)
        with open(dest, "w", encoding="utf-8", newline="\n") as f:
            f.write("".join(out))
        print(f"{dest}  ({os.path.getsize(dest) / 1024:.0f} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
